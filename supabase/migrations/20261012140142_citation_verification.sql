-- Citation verification is deliberately separate from the model review.  The
-- records below retain exactly what was parsed from a manuscript and what a
-- bibliographic provider returned, without storing manuscript prose as a
-- search query.

create table public.citation_verification_runs (
  id bigint generated by default as identity primary key,
  editor_id uuid not null references auth.users(id) on delete restrict,
  manuscript_id bigint not null,
  profile_version text not null default 'ijsds-citation-v1',
  run_status text not null default 'running'
    check (run_status in ('running', 'complete', 'partial', 'failed')),
  source_checksum text,
  reference_count integer not null default 0 check (reference_count >= 0),
  citation_count integer not null default 0 check (citation_count >= 0),
  verified_reference_count integer not null default 0 check (verified_reference_count >= 0),
  attention_reference_count integer not null default 0 check (attention_reference_count >= 0),
  error_summary text,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint citation_verification_runs_manuscript_editor_fkey
    foreign key (manuscript_id, editor_id)
    references public.manuscripts(id, editor_id)
    on delete restrict,
  constraint citation_verification_runs_id_editor_unique unique (id, editor_id)
);

create table public.reference_records (
  id bigint generated by default as identity primary key,
  editor_id uuid not null references auth.users(id) on delete restrict,
  manuscript_id bigint not null,
  run_id bigint not null,
  reference_order integer not null check (reference_order > 0),
  raw_reference text not null,
  doi text,
  first_author text,
  publication_year integer,
  title text,
  parsed_metadata jsonb not null default '{}'::jsonb,
  source_locator jsonb not null default '{}'::jsonb,
  verification_status text not null default 'pending'
    check (verification_status in ('pending', 'verified', 'verified_with_minor_metadata_difference', 'ambiguous_match', 'unlocatable', 'invalid_doi', 'manual_review')),
  verification_reason text,
  citation_count integer not null default 0 check (citation_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reference_records_run_editor_fkey
    foreign key (run_id, editor_id)
    references public.citation_verification_runs(id, editor_id)
    on delete restrict,
  constraint reference_records_manuscript_editor_fkey
    foreign key (manuscript_id, editor_id)
    references public.manuscripts(id, editor_id)
    on delete restrict,
  constraint reference_records_run_order_unique unique (run_id, reference_order),
  constraint reference_records_id_editor_unique unique (id, editor_id)
);

create table public.citation_occurrences (
  id bigint generated by default as identity primary key,
  editor_id uuid not null references auth.users(id) on delete restrict,
  manuscript_id bigint not null,
  run_id bigint not null,
  reference_id bigint,
  citation_text text not null,
  cited_author text,
  cited_year integer,
  source_locator jsonb not null default '{}'::jsonb,
  reconciliation_status text not null
    check (reconciliation_status in ('matched', 'ambiguous', 'missing_reference', 'manual_review')),
  created_at timestamptz not null default now(),
  constraint citation_occurrences_run_editor_fkey
    foreign key (run_id, editor_id)
    references public.citation_verification_runs(id, editor_id)
    on delete restrict,
  constraint citation_occurrences_manuscript_editor_fkey
    foreign key (manuscript_id, editor_id)
    references public.manuscripts(id, editor_id)
    on delete restrict,
  constraint citation_occurrences_reference_editor_fkey
    foreign key (reference_id, editor_id)
    references public.reference_records(id, editor_id)
    on delete restrict
);

create table public.reference_verifications (
  id bigint generated by default as identity primary key,
  editor_id uuid not null references auth.users(id) on delete restrict,
  manuscript_id bigint not null,
  run_id bigint not null,
  reference_id bigint not null,
  provider text not null check (provider in ('crossref', 'openalex')),
  lookup_type text not null check (lookup_type in ('doi', 'bibliographic', 'title')),
  request_fingerprint text not null,
  provider_work_id text,
  provider_url text,
  received_metadata jsonb not null default '{}'::jsonb,
  matched_fields jsonb not null default '{}'::jsonb,
  verification_status text not null
    check (verification_status in ('verified', 'verified_with_minor_metadata_difference', 'ambiguous_match', 'unlocatable', 'invalid_doi')),
  confidence numeric(4,3) not null check (confidence >= 0 and confidence <= 1),
  checked_at timestamptz not null default now(),
  constraint reference_verifications_run_editor_fkey
    foreign key (run_id, editor_id)
    references public.citation_verification_runs(id, editor_id)
    on delete restrict,
  constraint reference_verifications_reference_editor_fkey
    foreign key (reference_id, editor_id)
    references public.reference_records(id, editor_id)
    on delete restrict,
  constraint reference_verifications_manuscript_editor_fkey
    foreign key (manuscript_id, editor_id)
    references public.manuscripts(id, editor_id)
    on delete restrict
);

