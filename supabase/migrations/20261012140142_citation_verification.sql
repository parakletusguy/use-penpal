  on public.citation_verification_runs (manuscript_id, editor_id, created_at desc);
create index reference_records_run_status_idx
  on public.reference_records (run_id, verification_status, reference_order);
create index citation_occurrences_run_reconciliation_idx
  on public.citation_occurrences (run_id, reconciliation_status, id);
