-- Author-owned studio. This schema is intentionally separate from the protected
-- IJSDS editorial pilot and its editor-scoped manuscript records.

create table public.author_projects (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete restrict,
  title text not null check (char_length(trim(title)) between 1 and 240),
  research_area text,
  intended_journal text,
  journal_profile_version text not null default 'generic-pre-submission-v1',
  workspace_status text not null default 'active' check (workspace_status in ('active', 'archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, owner_id)
);

create table public.project_sources (
  id bigint generated by default as identity primary key,
  project_id bigint not null,
  owner_id uuid not null references auth.users(id) on delete restrict,
  citation text not null check (char_length(trim(citation)) between 1 and 4000),
  doi text check (doi is null or char_length(trim(doi)) between 1 and 512),
  source_url text check (source_url is null or char_length(trim(source_url)) between 1 and 2048),
  source_type text not null default 'bibliographic_record' check (source_type in ('bibliographic_record', 'user_note', 'uploaded_excerpt')),
  verification_status text not null default 'unverified' check (verification_status in ('unverified', 'author_confirmed', 'metadata_verified')),
  approved_for_synthesis boolean not null default false,
  approval_recorded_at timestamptz,
  created_at timestamptz not null default now(),
  constraint project_sources_approved_requires_confirmation check (approved_for_synthesis = false or (verification_status in ('author_confirmed', 'metadata_verified') and approval_recorded_at is not null)),
  constraint project_sources_project_owner_fkey foreign key (project_id, owner_id) references public.author_projects(id, owner_id) on delete cascade
);

create table public.research_tasks (
  id bigint generated by default as identity primary key,
  project_id bigint not null,
  owner_id uuid not null references auth.users(id) on delete restrict,
  prompt text not null check (char_length(trim(prompt)) between 1 and 4000),
  target_section text,
  task_status text not null default 'needs_sources' check (task_status in ('needs_sources', 'ready_for_grounded_draft', 'completed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint research_tasks_project_owner_fkey foreign key (project_id, owner_id) references public.author_projects(id, owner_id) on delete cascade
);

create table public.readiness_checks (
  id bigint generated by default as identity primary key,
  project_id bigint not null,
  owner_id uuid not null references auth.users(id) on delete restrict,
  criterion_key text not null check (char_length(trim(criterion_key)) between 1 and 120),
  criterion_label text not null check (char_length(trim(criterion_label)) between 1 and 400),
  guidance text not null check (char_length(trim(guidance)) between 1 and 2000),
  check_status text not null default 'not_started' check (check_status in ('not_started', 'needs_author_input', 'ready')),
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (project_id, criterion_key),
  constraint readiness_checks_project_owner_fkey foreign key (project_id, owner_id) references public.author_projects(id, owner_id) on delete cascade
);

create table public.author_audit_events (
  id bigint generated by default as identity primary key,
  project_id bigint,
  owner_id uuid not null references auth.users(id) on delete restrict,
  event_type text not null check (char_length(trim(event_type)) between 1 and 120),
  event_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint author_audit_events_project_owner_fkey foreign key (project_id, owner_id) references public.author_projects(id, owner_id) on delete cascade
);

create trigger set_author_projects_updated_at before update on public.author_projects for each row execute function penpal_private.set_updated_at();
create trigger set_research_tasks_updated_at before update on public.research_tasks for each row execute function penpal_private.set_updated_at();
create trigger set_readiness_checks_updated_at before update on public.readiness_checks for each row execute function penpal_private.set_updated_at();

create index author_projects_owner_updated_idx on public.author_projects (owner_id, updated_at desc);
create index project_sources_project_owner_created_idx on public.project_sources (project_id, owner_id, created_at desc);
create index project_sources_project_approved_idx on public.project_sources (project_id, owner_id) where approved_for_synthesis = true;
create index research_tasks_project_owner_updated_idx on public.research_tasks (project_id, owner_id, updated_at desc);
create index readiness_checks_project_owner_idx on public.readiness_checks (project_id, owner_id, created_at);
create index author_audit_events_project_owner_created_idx on public.author_audit_events (project_id, owner_id, created_at desc);

revoke all on table public.author_projects, public.project_sources, public.research_tasks, public.readiness_checks, public.author_audit_events from anon, authenticated, service_role;
grant select, insert, update on table public.author_projects, public.project_sources, public.research_tasks, public.readiness_checks to authenticated;
grant select, insert on table public.author_audit_events to authenticated;
grant select, insert, update, delete on table public.author_projects, public.project_sources, public.research_tasks, public.readiness_checks, public.author_audit_events to service_role;
grant usage, select on sequence public.author_projects_id_seq, public.project_sources_id_seq, public.research_tasks_id_seq, public.readiness_checks_id_seq, public.author_audit_events_id_seq to authenticated, service_role;

