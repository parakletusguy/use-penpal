-- PenPal Phase 1: editor-owned manuscript workspace.
-- This migration deliberately keeps originals, generated artefacts, review evidence,
-- and editor decisions separate so every substantive change is traceable.

create schema if not exists penpal_private;
revoke all on schema penpal_private from public;

create function penpal_private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table public.import_batches (
  id bigint generated by default as identity primary key,
  editor_id uuid not null references auth.users(id) on delete restrict,
  source_provider text not null default 'google_drive'
    check (source_provider in ('google_drive')),
  source_folder_id text not null,
  source_folder_name text not null,
  import_status text not null default 'draft'
    check (import_status in ('draft', 'validating', 'ready_to_import', 'importing', 'complete', 'attention', 'failed')),
  total_files integer not null default 0 check (total_files >= 0),
  valid_file_count integer not null default 0 check (valid_file_count >= 0),
  attention_file_count integer not null default 0 check (attention_file_count >= 0),
  imported_file_count integer not null default 0 check (imported_file_count >= 0),
  import_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (id, editor_id)
);

create table public.manuscripts (
  id bigint generated by default as identity primary key,
  editor_id uuid not null references auth.users(id) on delete restrict,
  batch_id bigint not null,
  source_file_id text not null,
  source_file_name text not null,
  source_mime_type text,
  source_file_modified_at timestamptz,
  source_checksum text,
  title text,
  original_storage_path text,
  extracted_text_storage_path text,
  workflow_status text not null default 'imported'
    check (workflow_status in ('imported', 'checking', 'needs_attention', 'ready_to_review', 'ready_to_edit', 'ready_to_export', 'exported', 'failed')),
  consent_status text not null default 'needs_confirmation'
    check (consent_status in ('recorded', 'needs_confirmation', 'not_recorded', 'withdrawn')),
  consent_recorded_at timestamptz,
  consent_verified_by uuid references auth.users(id) on delete restrict,
  current_edit_version integer not null default 0 check (current_edit_version >= 0),
  analysis_started_at timestamptz,
  analysis_completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint manuscripts_batch_editor_fkey
    foreign key (batch_id, editor_id)
    references public.import_batches(id, editor_id)
    on delete restrict,
  constraint manuscripts_source_file_per_editor_unique unique (editor_id, source_file_id),
  constraint manuscripts_id_editor_unique unique (id, editor_id),
  constraint manuscripts_recorded_consent_has_timestamp
    check (consent_status <> 'recorded' or consent_recorded_at is not null),
  constraint manuscripts_processing_requires_recorded_consent
    check (
      consent_status = 'recorded'
      or workflow_status not in ('checking', 'ready_to_review', 'ready_to_edit', 'ready_to_export', 'exported')
    )
);

create table public.review_reports (
  id bigint generated by default as identity primary key,
  editor_id uuid not null references auth.users(id) on delete restrict,
  manuscript_id bigint not null,
  report_status text not null default 'draft'
    check (report_status in ('draft', 'final')),
  rubric_version text not null,
  model_provider text,
  summary text,
  report_content jsonb not null default '{}'::jsonb,
  generated_at timestamptz,
  finalised_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint review_reports_manuscript_editor_fkey
    foreign key (manuscript_id, editor_id)
    references public.manuscripts(id, editor_id)
    on delete restrict,
  constraint review_reports_manuscript_unique unique (manuscript_id)
);

create table public.findings (
  id bigint generated by default as identity primary key,
  editor_id uuid not null references auth.users(id) on delete restrict,
  manuscript_id bigint not null,
  finding_type text not null
    check (finding_type in ('technical', 'formatting', 'citation', 'language', 'metadata', 'ethical')),
  severity text not null
    check (severity in ('info', 'warning', 'high', 'blocking')),
  finding_status text not null default 'open'
    check (finding_status in ('open', 'dismissed', 'resolved')),
  title text not null,
  description text not null,
  evidence_excerpt text,
  source_locator jsonb not null default '{}'::jsonb,
  recommended_action text,
  requires_editor_decision boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint findings_manuscript_editor_fkey
    foreign key (manuscript_id, editor_id)
    references public.manuscripts(id, editor_id)
    on delete restrict,
  constraint findings_id_editor_unique unique (id, editor_id)
);

create table public.edit_suggestions (
  id bigint generated by default as identity primary key,
  editor_id uuid not null references auth.users(id) on delete restrict,
  manuscript_id bigint not null,
  finding_id bigint,
  suggestion_type text not null
    check (suggestion_type in ('grammar', 'clarity', 'formatting', 'citation', 'consistency', 'author_query')),
  suggestion_status text not null default 'proposed'
    check (suggestion_status in ('proposed', 'approved', 'rejected', 'modified', 'applied')),
  source_locator jsonb not null default '{}'::jsonb,
  original_text text,
  proposed_text text,
  rationale text not null,
  decision_note text,
  decided_by uuid references auth.users(id) on delete restrict,
  decided_at timestamptz,
  applied_in_version integer check (applied_in_version is null or applied_in_version > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint edit_suggestions_manuscript_editor_fkey
    foreign key (manuscript_id, editor_id)
    references public.manuscripts(id, editor_id)
    on delete restrict,
  constraint edit_suggestions_finding_editor_fkey
    foreign key (finding_id, editor_id)
    references public.findings(id, editor_id)
    on delete restrict
);

create table public.document_artifacts (
  id bigint generated by default as identity primary key,
  editor_id uuid not null references auth.users(id) on delete restrict,
  manuscript_id bigint not null,
  artifact_type text not null
    check (artifact_type in ('original', 'extracted_text', 'revised_manuscript', 'review_report', 'change_log')),
  storage_path text not null,
  display_name text not null,
  content_type text,
  checksum text,
  byte_size bigint check (byte_size is null or byte_size >= 0),
  generated_from_version integer check (generated_from_version is null or generated_from_version >= 0),
  created_by uuid references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint document_artifacts_manuscript_editor_fkey
    foreign key (manuscript_id, editor_id)
    references public.manuscripts(id, editor_id)
    on delete restrict,
  constraint document_artifacts_storage_path_unique unique (storage_path)
);

create table public.audit_events (
  id bigint generated by default as identity primary key,
  editor_id uuid not null references auth.users(id) on delete restrict,
  manuscript_id bigint,
  event_type text not null,
  entity_type text not null,
  entity_id bigint,
  event_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint audit_events_manuscript_editor_fkey
    foreign key (manuscript_id, editor_id)
    references public.manuscripts(id, editor_id)
    on delete restrict
);

