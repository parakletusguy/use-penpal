-- Private bucket and ownership-scoped paths: <editor UUID>/<manuscript ID>/<file name>.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'penpal-manuscripts',
  'penpal-manuscripts',
  false,
  52428800,
  array[
    'application/pdf',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'application/msword'
  ]
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

create policy "editors can read their manuscript objects"
  on storage.objects for select to authenticated
  using (
    bucket_id = 'penpal-manuscripts'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );
create policy "editors can upload their manuscript objects"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'penpal-manuscripts'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );
